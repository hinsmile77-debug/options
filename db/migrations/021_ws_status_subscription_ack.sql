-- Mahdi 추가 (2026-08-03, 운영점검보고서 2026-08-03 §2-4 / §4 우선순위 4) — 구독 성립 시각.
--
-- 08-03 하루 H0UNMKO0(장운영정보) 수신 **0건**이었다(07-31은 08:00에 1건). 08-01에 넣은 독립
-- 하트비트는 예측대로 작동해 `market_halt_status.updated_at`이 15:41:06까지 갱신됐지만,
-- **바로 그것이 "수신 0건"을 가려주는 효과**도 함께 냈다 — 화면은 초록불인데 감지기가 실제로
-- 무언가에 붙어 있는지는 아무도 모르는 상태다(main.py:163이 정직하게 남겨둔 한계가 실현됐다).
--
-- 그렇다고 `last_message_at`에 임계를 걸 수는 없다. H0UNMKO0은 세션 전이 시에만 오므로 정상일에도
-- 하루 0~2건이고, 임계를 두면 상시 오경보가 된다(2026-07-31 §2-2에서 이미 확인한 사실).
--
-- 대신 **구독 요청에 대한 KIS의 응답(SUBSCRIBE ACK)** 을 남긴다. 이것은 데이터 유무와 무관하게
-- "구독이 성립했다"를 증명하며, WS 재연결 시 재구독마다 갱신된다.
--   market_op_subscribed_at  H0UNMKO0 구독이 마지막으로 성립한 시각. NULL이면 한 번도 성립 안 함.
--
-- 원칙은 2026-08-01과 같다: **생존 신호는 감시 대상과 독립해야 한다.** 여기서 감시 대상은
-- "장운영정보 데이터"이고, 독립한 신호는 "구독 성립"이다.

ALTER TABLE ws_status ADD COLUMN IF NOT EXISTS market_op_subscribed_at TIMESTAMPTZ;

COMMENT ON COLUMN ws_status.market_op_subscribed_at IS
    'H0UNMKO0(장운영정보) 구독이 마지막으로 성립한 시각 — KIS의 SUBSCRIBE 응답(rt_cd=0) 수신 시점. '
    'NULL이면 이번 기동에서 한 번도 성립하지 않았다는 뜻이고, 이는 last_message_at이 비어 있는 것과 '
    '**전혀 다른 신호**다(정상일에도 장운영정보 데이터는 하루 0~2건이라 last_message_at에는 임계를 '
    '걸 수 없다 — 2026-07-31 §2-2). naive KST 벽시계가 "+00"으로 라벨링된 값(local_now() 정책).';
