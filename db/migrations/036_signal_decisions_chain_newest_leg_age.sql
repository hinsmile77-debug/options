-- Mahdi 추가 (2026-09-02, 09-02 §1-11 / 제4부 P1-5) — 신선도를 **이산에서 연속으로**.
--
-- **왜 필요한가**: 마이그레이션 029가 만든 `chain_input_source`는 «그 분 것인가»라는 이산
-- 질문에 답한다. 그것이 029의 목적이었고 08-11에는 옳았다 — 그때는 하루의 절반이 stale이라
-- 이진값으로도 갈렸다. 그런데 08-18 이후 그 값은 **매일 98~100% stale**로 상한에 붙어 있다.
--
--   08-18 100.0 / 08-19 98.8 / 08-20 95.3 / 08-21 88.4 / 09-01 98.8 / 09-02 99.2
--
-- 이 상태에서는 **개선이 보이지 않는다.** 판정이 「최신 먼슬리 레그의 분 == 판단 시각의 분」
-- 이라 1초를 어긋나도 100% stale이고, 1분 늦은 체인과 3분 늙은 체인이 같은 칸에 들어간다.
-- 09-02 §1-11이 이 지표를 레버 E의 「주장」 축으로 쓴 것이 왜 반증만 냈는지 코드로 확인한 자리다.
--
-- **이 컬럼이 재는 것**: 판단 시각(`now`) − 스냅샷에서 **가장 새로운** 먼슬리 레그의 타임스탬프.
-- `chain_input_source`를 만든 바로 그 값(`newest`)을 초 단위로도 남기는 것이다 — 즉 **같은
-- 관측의 연속판**이고, 두 값은 서로를 검산한다(`< 60초` ⟺ `current` — 레그 타임스탬프가
-- 분 단위로 잘려 있으므로 이 나이는 곧 「판단 초 + 마이크로초」다).
--
--   chain_oldest_leg_age_seconds (022)  스냅샷에서 **가장 오래된** 레그 — «창이 얼마나 넓은가»
--   chain_newest_leg_age_seconds (036)  스냅샷에서 **가장 새로운** 레그 — «얼마나 최신인가»
--   chain_input_source           (029)  위 값이 그 분 안인가 (이산 요약)
--
-- ⚠ **029를 대체하지 않는다.** 정의를 바꾸면 08-11 이후 전 이력과의 비교가 끊긴다
-- (09-02 제4부 P1-5의 회귀 위험 항목). 두 값을 **나란히** 낸다.
--
--   NULL  이 컬럼 이전(2026-09-02 이전) 행이거나, 그 분에 먼슬리 레그가 없었다(= `none`).
--         전자와 후자는 `chain_input_source`가 갈라 준다 — 그쪽이 NULL이면 「못 쟀다」,
--         `'none'`이면 「쟀는데 없었다」다(029 주석과 같은 구분).

ALTER TABLE signal_decisions ADD COLUMN IF NOT EXISTS chain_newest_leg_age_seconds DOUBLE PRECISION;

COMMENT ON COLUMN signal_decisions.chain_newest_leg_age_seconds IS
    '판단 시각 − 스냅샷에서 가장 새로운 먼슬리 레그의 타임스탬프(초, 2026-09-02 P1-5). '
    'chain_input_source(029)의 연속판이며 그것을 대체하지 않는다 — 029는 분 단위 이산 판정이라 '
    '08-18 이후 매일 98~100% stale로 상한에 붙어 개선 폭이 안 보였다. '
    'chain_oldest_leg_age_seconds(022)가 스냅샷 창의 너비라면 이 값은 그 창의 최신 끝이다. '
    'NULL=이 컬럼 이전 행이거나 그 분에 먼슬리 레그가 없었다(chain_input_source가 둘을 가른다).';
