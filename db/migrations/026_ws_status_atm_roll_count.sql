--
-- **왜 필요한가**: 08-03에 "행사가 창이 하루 종일 한 번도 안 움직였다"(그날 하루치 체인 전체가
-- 스팟에서 5.5% 떨어진 외가격에서 수집됐다)를 고치면서 선물 1분봉마다 재롤링하게 됐다.
-- 그런데 **그 반대편 비용은 계측되지 않았다.** 08-05 실측: 08:46~12:20 사이 **77회**
-- (평균 2.7분마다). 선물이 격자 중간점(1.25p)을 오갈 때마다 창이 흔들린다.
--
-- 롤 한 번마다 창을 벗어난 종목은 WS 구독이 해제되고 그 종목의 1분봉이 끊긴다. 08-05 COCKPIT
-- Flow Radar가 옵션 B09F9WA21의 11:26~12:02를 직선으로 그리고 있었던 것(P0-1)이 정확히 그
-- 결과다 — 로그로 확인한 실제 구간은 11:27:02 구독 해제 ~ 12:02:01 재구독이었다.
--
-- 즉 이 숫자는 **관측 연속성의 직접적인 선행지표**인데, 알아내려면 로그의 "ATM 롤링" 줄을
-- 세야 했다(그것도 북마다 한 줄씩 남아 3으로 나눠야 한다). 07-31에 REST 수요를 계량하기 전과
-- 똑같은 상태다: 지표는 있는데 그날 볼 수 없다.
--
-- **왜 ws_status인가**: 구독 상태와 같은 도메인이고, 이미 같은 방식으로 관리되는 이웃
-- (`reconnect_count_today`)이 있다 — 관측 루프가 메모리에서 증가시키고 독립 하트비트
-- (`poll_ws_heartbeat`, 300초)가 DB에 남긴다. 프로세스가 매일 아침 새로 뜨므로 "오늘" 카운트는
-- 자연히 초기화된다(별도 리셋 로직을 두면 그것이 또 틀릴 여지가 된다).
--
--   atm_roll_count_today  창이 **실제로 이동한** 횟수. 북(먼슬리/위클리 월·목)이 여러 개라도
--                         "창이 한 번 움직였다"를 1로 센다 — 로그 줄 수를 북 수로 나누는 방식은
--                         북 수가 바뀔 때 조용히 틀린다.

