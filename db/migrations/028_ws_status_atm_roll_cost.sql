-- Mahdi 추가 (2026-08-07, 운영점검 §B-1 / 고도화#2) — ATM 롤의 **대가**를 센다.
--
-- **왜 횟수로는 부족한가**: 026이 도입한 `atm_roll_count_today`는 배지 임계 20회를 이틀 연속
-- 4배 가까이 넘겼다(08-05 77회 / 08-07 76회). 그런데 08-07에 롤 76회를 전수 검산하니 **전부
-- 히스테리시스 임계(2.5 x 0.75 = 1.875p)를 정당하게 넘은 것**이었다 — 그날 지수가 1004~964~982
-- (40p)를 오갔고 격자가 2.5p라, 어떤 임계값을 써도 그 왕복은 남는다.
--
-- 즉 **롤 횟수는 시장 변동성의 함수이고 우리가 통제할 수 없다.** 임계를 20에 두면 변동성 있는
-- 날마다 울리는 상시 경고가 되고, 상시 경고는 곧 안 읽는 경고다. 026 주석이 정확히 말했듯
-- 우리가 실제로 걱정하는 것은 롤 자체가 아니라 **"창을 벗어난 종목의 구독이 해제돼 그 종목
-- 1분봉이 끊기는 것"** 이다. 그렇다면 그것을 직접 세야 한다.
--
-- 2026-08-07 고도화#1(`SubscriptionRetentionPool`)이 슬롯이 남는 동안 구독을 유지하도록 바꿨으므로,
-- 이제 롤 횟수와 끊긴 구독 수는 **분리된다**: 롤 76회 / 끊긴 구독 0건이면 대가 없이 창만 따라간
-- 것이고, 그것이 목표 상태다.
--
--   atm_roll_dropped_subs_today  롤 때문에 **실제로 해제된** WS 구독 수(종목 단위, 누적).
--                                유지 풀이 슬롯 부족으로 축출한 건수다. 0이면 대가가 없었다.
--                                NULL = 아직 아무도 안 셌다(026과 같은 이유로 DEFAULT를 두지
--                                않는다 — 구 코드로 도는 관측 루프가 DEFAULT 0을 남기면
--                                "대가가 없었다"는 거짓말이 된다).
ALTER TABLE ws_status ADD COLUMN IF NOT EXISTS atm_roll_dropped_subs_today INTEGER;

COMMENT ON COLUMN ws_status.atm_roll_dropped_subs_today IS
    'ATM 롤로 실제 해제된 WS 구독 수(2026-08-07 고도화#2). 롤 횟수(atm_roll_count_today)는 '
    '시장 변동성의 함수라 통제 불가지만, 이 값은 구독 유지 풀(SubscriptionRetentionPool)이 '
    '슬롯 부족으로 축출한 건수라 우리가 통제한다 — 끊긴 1분봉의 직접 지표다. 0이 목표.';
