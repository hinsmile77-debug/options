-- Mahdi 추가 (2026-08-04, 운영점검보고서 2026-08-04 §2-8 / Fix#5) — GEX를 어느 북으로 냈는가.
--
-- **왜 필요한가**: 08-04에 `_build_signal_inputs()`가 `legs_from_chain_rows()`로 세 만기
-- (먼슬리 + 위클리 월/목)를 **평탄화해서 한 덩어리로** GEX/감마플립을 계산하고 있는 것이
-- 드러났다. 그런데 v6 §11.4와 자동 리포트 §15 각주는 둘 다
--   *"먼슬리(최근월)가 GEX/감마플립의 주 입력이고, 위클리는 핀 리스크 전용으로 읽는다"*
-- 고 적고 있었다 — **코드가 문서와 다르게 동작했다.**
--
-- 피해가 구체적이다(08-04 실측): 08-06 위클리는 GEX +90.8B(콜 편중), 08-13 먼슬리는 −51.0B
-- (풋 편중)로 **부호가 반대**다. 합치면 두 북이 서로를 상쇄해, 라이브 GEX가 하루 동안
-- −33.5B ~ +99.1B를 오가며 양수 233분 / 음수 259분이 됐다. `_options_flow_score()`는 GEX
-- 부호로 회귀/증폭을 가르므로(signal_layer.py) 이 혼합이 **신호의 부호를 직접 좌우했다.**
--
-- Fix#5로 판단 입력을 먼슬리 전용으로 바꾸는데, 그 효과를 사후에 확인하려면 "그 분의 GEX가
-- 어느 만기의 것인가"가 판단 행에 남아야 한다. 안 남기면 08-03 §5-1이 겪은 것과 같은 상황
-- (지표가 나빠졌는데 원인을 되짚을 데이터가 없음)이 반복된다.
--
--   gex_expiry  그 분의 gex/gamma_flip을 계산한 북의 만기일. NULL = 체인이 비어 계산 자체를
--               못 한 분(기존 gex/gamma_flip NULL과 같은 의미). 이 값이 위클리 만기로 찍히는
--               분이 있으면 먼슬리 식별(`db_metrics.monthly_book_expiry()`)이 실패한 것이다 —
--               그 함수는 만기유동성 폴러 첫 행(08:31 부근) 이전에는 None을 돌려주므로,
--               장전 구간에는 폴백(최근월 = 가장 먼 만기)이 찍힐 수 있다.

ALTER TABLE signal_decisions ADD COLUMN IF NOT EXISTS gex_expiry DATE;

COMMENT ON COLUMN signal_decisions.gex_expiry IS
    '판단 시점의 gex/gamma_flip을 계산한 북의 만기일(2026-08-04 §2-8 / Fix#5). 종전에는 세 만기를 '
    '평탄화해 합산했고, 부호가 반대인 북끼리 상쇄돼 라이브 GEX가 하루 492분 중 233분 양수 / '
    '259분 음수로 오갔다. v6 §11.4는 먼슬리(최근월)를 주 입력으로 규정한다 — 이 컬럼이 그 규정이 '
    '실제로 지켜졌는지를 사후에 확인하는 유일한 근거다.';
