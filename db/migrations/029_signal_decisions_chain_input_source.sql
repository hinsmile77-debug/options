-- Mahdi 추가 (2026-08-11, 운영점검보고서 2026-08-11 §5-B / 고도화 B) — 판단이 본 체인의 **출처**.
--
-- **왜 필요한가**: 08-11 장중 점검에서 `signal_decisions.gex`가 짝수분마다 직전 값을 반복하는
-- 것이 눈에 띄었다. 체인 나이로 검정하니 원인이 나왔다(09:00 이후 실측):
--
--     홀수분(먼슬리 10레그)   체인 나이 평균 28.0초    폴링 9.2초  < 판단 위상 10초
--     짝수분(양 북 20레그)    체인 나이 평균 70.0초    폴링 19.3초 > 판단 위상 10초
--
-- `poll_option_chain`은 :00에 시작하고 `poll_signal_fusion_cycle`은 :10에 판단한다. 짝수분에는
-- 그 분 체인이 아직 안 들어와 **`option_chain_as_of()`의 신선도 창이 직전 분 스냅샷을 실어준다.**
--
-- 즉 하루의 절반이 1분 늙은 GEX로 판단하고 있었고, **그 사실이 어떤 지표에도 없었다.**
-- `chain_oldest_leg_age_seconds`(마이그레이션 022)가 있었지만 그것은 초 단위 연속값이라
-- "이 분 것인가 아닌가"라는 이산 질문에 답하지 않는다 — 08-06 §2-4가 같은 함정에 빠졌던 자리다
-- (그때는 격분 설계상수 130초를 신선도로 착각했다).
--
-- 022/023/024가 "판단이 **무엇을** 봤는가"를 남긴 것과 같은 이유로, 이 컬럼은
-- "판단이 **언제 것을** 봤는가"를 남긴다. 사후에 로그를 안 뒤져도 귀속이 갈린다.
--
--   chain_input_source  'current'  그 분에 적재된 체인으로 판단했다(정상)
--                       'stale'    신선도 창이 직전 분(이상) 스냅샷을 실어줬다
--                       'none'     체인이 아예 없었다 — 그 분은 GEX 입력이 없다(§14 불변식)
--                       NULL       이 컬럼 이전(2026-08-11 이전)에 기록된 행
--
-- **NULL과 'none'은 다르다**: 전자는 "못 쟀다", 후자는 "쟀는데 없었다"이다. 이 구분이 없으면
-- 08-11 이전 이력이 전부 "체인 없음"으로 보여 §14의 `gex_input_missing_minutes`가 오염된다.

ALTER TABLE signal_decisions ADD COLUMN IF NOT EXISTS chain_input_source VARCHAR(10);

COMMENT ON COLUMN signal_decisions.chain_input_source IS
    '판단이 본 체인의 출처(2026-08-11 고도화 B). current=그 분 적재분 / stale=신선도 창이 실어준 '
    '직전 분 이상 / none=체인 없음 / NULL=이 컬럼 이전 행. 08-11 실측에서 짝수분(20레그, 폴링 19.3초)이 '
    '판단 위상(:10초)보다 늦어 하루의 절반이 stale이었고, 그 사실이 어떤 지표에도 없었다. '
    'chain_oldest_leg_age_seconds(초 단위 연속값)로는 "이 분 것인가"라는 이산 질문에 답할 수 없다.';
